/**
 *******************************************************************************
 * @file    app_config.h
 * @brief   应用层的可调参数(只放应用策略, 不放组件内部参数)
 *
 * 分层: osal(系统抽象) -> bsp(驱动) -> service(业务组件) -> app(装配, 本文件所在层)。
 * 组件自己的周期/栈/优先级/队列深度定义在各自头文件里(SVC_xxx_*), 不在本文件。
 *
 * 任务一览(**任务创建全部在 5 个 *_app.c 的 Xxx_App_Start() 里**):
 *
 *   任务      周期/唤醒              职责                          在哪建
 *   --------  ---------------------  ----------------------------  -----------
 *   net       2 ms 轮询              独占 lwIP, 收发包 + 命令分发   inter_app
 *   key       20 ms 轮询             消抖 + 复位/重连 + 上报按键     inter_app
 *   led       队列阻塞              呼吸灯掩码/频率                monitor_app
 *   monitor   1000 ms                一行状态日志 + 过流巡检         monitor_app
 *   ls        5 ms 采样              光幕 6 路采样 + 消抖 + 上报     brake_app
 *   brake     5 ms                   制动时序 + 过流保护             brake_app
 *   rs485     唤醒/超时              半双工发送 + 总线锁             Mover_app
 *   mover     时序到点唤醒           发射整周期逐帧推进              Mover_app
 *   ads       10 ms                  独占 PS SPI0, 8 路 ADC          samp_app
 *   emmc      200 ms 轮询            样本写卡 + 每秒 sync            samp_app
 *******************************************************************************
 */

#ifndef APP_CONFIG_H
#define APP_CONFIG_H

/* ========================================================================== */
/*  组件开关: 关掉 = 这个组件完全不参与(不初始化、不起任务)                     */
/* ========================================================================== */

/** 光幕组件(LS_I 6 路输入采样 + 上报)。 */
#define APP_ENABLE_LS           1U

/** RS-485 组件(半双工总线 + 总线锁)。 */
#define APP_ENABLE_RS485        1U

/** ADS8688 采集组件(独占 PS SPI0, 8 路 ADC)。 */
#define APP_ENABLE_ADS          1U

/**
 * 直线电机组件(Modbus RTU + CiA402, 命令 0xD0..0xD6)。
 * 依赖 APP_ENABLE_RS485: 它借 RS-485 组件的总线和总线锁。
 */
#define APP_ENABLE_MOTOR        1U

/**
 * eMMC 记录组件(FatFs)。1 = 采样一跑就自动录到卡上。
 * 依赖 APP_ENABLE_ADS: 数据由 ADS 组件每 10 ms 通过订阅回调推过来。
 * 没插卡/没格式化时不影响其它功能, 组件自己进"没卡"状态, 上电打一行警告。
 */
#define APP_ENABLE_EMMC         1U

/** PS 端按键组件(KEY1 = MIO10 软复位, KEY2 = MIO11 保留)。 */
#define APP_ENABLE_KEY          1U

/* ========================================================================== */
/*  按键策略                                                                   */
/* ========================================================================== */

/**
 * 1 = KEY2 的动作(重启 TCP 服务端)启用; 0 = 保留不使用。
 * 0 时引脚照常读/消抖/计数并照常上报, 只是不做动作; 网口敲 0xAC 回 disabled。
 */
#define APP_KEY2_RESTART_ENABLE 0U

/** 按键轮询周期(ms)。 */
#define APP_KEY_POLL_MS         20U

/** 连续几次采到同一电平才算稳定(3 x 20 ms = 60 ms)。 */
#define APP_KEY_DEBOUNCE        3U

/** 上电后多少毫秒之内不响应按键(防按键卡住导致反复复位)。 */
#define APP_KEY_ARM_DELAY_MS    3000U

/** 1 = 按下时读到低电平(按键接 GND, MIO 内部上拉)。 */
#define APP_KEY_ACTIVE_LOW      1U

/* ========================================================================== */
/*  呼吸灯(4 路, breath_led IP)                                                */
/* ========================================================================== */

/*
 *   LED0 = K16   LED1 = J16   LED2 = K14   LED3 = J14
 *   四路共用一个呼吸频率(IP 里只有一个 PERIOD 寄存器), 每颗灯只有"灭/呼吸"两种状态。
 *   命令: 0xF0 全灭 / 0xF1..0xF3 慢·标准·快 / 0xF4 查状态 / 0xF5 全亮 /
 *         0xF6..0xF9 点亮 LED0..3 / 0xFA..0xFD 熄灭 LED0..3 /
 *         0xFE <频率/10> / 0xFF <掩码>
 */

/** 1 = 用指示灯那一路做"网口在线"指示(有客户端呼吸, 最后一个客户端断开就熄灭)。 */
#define APP_LED_LINK_INDICATOR  1U

/** "网口在线"用哪一颗灯(0..3)。 */
#define APP_LED_LINK_INDEX      0U

/** 在线指示的呼吸频率(写 PERIOD 寄存器; 明暗周期 = 100000 / 本值 毫秒, 范围 10..1000)。 */
#define APP_LED_LINK_FREQ_HZ    100U

/* ========================================================================== */
/*  网口策略(传给 Svc_Net_Init)                                                */
/* ========================================================================== */

/** 1 = 用 DHCP; 0 = 用 bsp/enet/enet_cfg.h 里的静态地址。 */
#define APP_NET_USE_DHCP        0U

/** DHCP 等待时间(ms), 超时就回落到静态地址。 */
#define APP_NET_DHCP_TIMEOUT_MS 12000U

/** TCP 服务端口(上位机连这个口)。 */
#define APP_NET_TCP_PORT        7U

/* ========================================================================== */
/*  监视组件策略(传给 Svc_Mon_Init)                                            */
/* ========================================================================== */

/** 状态日志周期(ms)。 */
#define APP_MON_PERIOD_MS       1000U

/** 每多少次状态日志打一次完整状态。 */
#define APP_MON_FULL_DIV        5U

/**
 * 1 = 过流引脚恢复后由监控任务自动确认; 0 = 只报警, 确认交给制动业务(0xA5 关闭制动时清)。
 * 现在用 0: 过流由 brake 任务接管, 自动确认会把硬件粘滞位(哪个桥过流)提前清掉。
 */
#define APP_PWM_OC_AUTO_ACK     0U

#endif /* APP_CONFIG_H */
