/**
 *******************************************************************************
 * @file    service_rs485.h
 * @brief   半双工 RS485 发送 + 总线锁(AXI UARTLite + DE 方向脚)
 *
 * 只发不收, 不组帧、不解析协议: 这里是驱动级组件, 只把字节搬上总线。
 * 要在这条总线上跑协议就在协议组件里调 Svc_Rs485_Send(), 已有一个同目录的 service_motor。
 *
 * 中断顺序(别改): 第一次连接中断会重新初始化 GIC(lwIP 的 xemac_add() 就会做),
 * 所以 Rs485_Start() 必须在网络组件之后调 —— 本组件把它放在 rs485 任务里执行。
 *******************************************************************************
 */

#ifndef SERVICE_RS485_H
#define SERVICE_RS485_H

#include <stdint.h>

#include "service/service.h"

/* -------------------------------------------------------------------------- */
/*  组件参数                                                                   */
/* -------------------------------------------------------------------------- */

#define SVC_RS485_STACK_WORDS   1024U   /**< 4 KB(任务只 Start 一次就睡)      */
#define SVC_RS485_PRIO          3U      /**< 和 ads/rs485 同级, 低于 net(4)   */

/* -------------------------------------------------------------------------- */
/*  总线锁                                                                     */
/* -------------------------------------------------------------------------- */

/**
 * @brief  拿住 / 放开总线锁(递归互斥量, 持锁期间再调 Send 不会死锁)。
 *
 * 半双工时"我这一轮发言"必须是一个整体, 否则别的调用者会插进来把 DE 抢走:
 *     Svc_Rs485_BusLock(); Svc_Rs485_Send(f, n); Svc_Rs485_BusUnlock();
 */
void Svc_Rs485_BusLock(void);
void Svc_Rs485_BusUnlock(void);

/* -------------------------------------------------------------------------- */
/*  对外接口                                                                     */
/* -------------------------------------------------------------------------- */

/** @brief  初始化 AXI UARTLite + DE 方向脚 + 建总线锁。 */
Svc_StatusTypeDef Svc_Rs485_Init(void);

/** @brief  初始化好了没有(1 = 好了)。应用层据此决定要不要建任务。 */
uint8_t Svc_Rs485_IsReady(void);

/** @brief  rs485 任务入口(调 Rs485_Start() 起端口); 任务由应用层创建。 */
void Svc_Rs485_Task(void *Arg);

/** @brief  发一段字节(阻塞式半双工: 发完并放开 DE 才返回)。 */
Svc_StatusTypeDef Svc_Rs485_Send(const uint8_t *Data, uint16_t Len);

#endif /* SERVICE_RS485_H */
