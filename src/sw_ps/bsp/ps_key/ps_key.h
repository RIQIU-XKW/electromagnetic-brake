/**
 *******************************************************************************
 * @file    ps_key.h
 * @brief   PS 端按键 —— MIO 上的两个按键(读电平)
 *
 * 硬件(走 PS 的 MIO, 不占 PL 引脚):
 *     KEY1 -> MIO10 (封装球 E9)   软复位(重启软件/硬件初始化)
 *     KEY2 -> MIO11 (封装球 C6)   重连网络(TCP 服务端重启)
 *
 * 不用改 BD / XDC: MIO 是 PS 内部引脚, XDC 里不写约束; PS7 已开 MIO GPIO,
 * MIO10/11 没被任何外设占用; 内部上拉已打开, 另一端接 GND 就是"按下 = 低电平"。
 *
 * XGpioPs 的 API 有两个版本, 由 SDT 宏切换: 本工程带 -DSDT(为 xilffs 加的, 但它让
 * 整个 BSP 头文件族都走 SDT 分支), 所以必须用基地址版
 * XGpioPs_LookupConfig(BaseAddress) —— 网上那套 DEVICE_ID 版在本工程编不过。
 *******************************************************************************
 */

#ifndef BSP_PS_KEY_H
#define BSP_PS_KEY_H

#include <stdint.h>

/* -------------------------------------------------------------------------- */
/*  硬件绑定                                                                   */
/* -------------------------------------------------------------------------- */

/** KEY1 的 MIO 编号(全局引脚号, MIO10 -> 10)。 */
#define PS_KEY_MIO_KEY1     10U

/** KEY2 的 MIO 编号(MIO11 -> 11)。 */
#define PS_KEY_MIO_KEY2     11U

/* -------------------------------------------------------------------------- */
/*  类型定义                                                                     */
/* -------------------------------------------------------------------------- */

typedef enum {
    PS_KEY_OK        =  0,
    PS_KEY_ERR_PARAM = -1,
    PS_KEY_ERR_HW    = -2       /**< XGpioPs 初始化失败                          */
} PsKey_StatusTypeDef;

/* -------------------------------------------------------------------------- */
/*  对外接口                                                                     */
/* -------------------------------------------------------------------------- */

/**
 * @brief  初始化 PS GPIO 并把两个按键配成输入。
 * @note   只配方向, 不碰内部上拉(那是 ps7_init 做的, 运行期改容易和硬件设计打架)。
 *         可以在调度器起来之前调。
 */
PsKey_StatusTypeDef PsKey_Init(void);

/** @brief  初始化成功过没有(0/1)。读之前先看这个, 免得读到假电平。 */
uint8_t PsKey_Ready(void);

/** @brief  读某一 MIO 的原始电平; 未初始化或参数非法返回 1(即"没按下", 偏安全侧)。 */
uint8_t PsKey_ReadLevel(uint32_t Mio);

#endif /* BSP_PS_KEY_H */
